"""Abstract base interface for swappable LLM backends.

Design Decision:
By defining an explicit Abstract Base Class (`LLMClient`), the rest of the application
(FastAPI, Streamlit, and eval scripts) depends only on the contract `generate(prompt: str) -> str`.
This allows seamless switching between cloud (Gemini) and offline/local private deployment (Ollama)
via a single environment variable without changing any application code.
"""

from abc import ABC, abstractmethod


class LLMClient(ABC):
    """Abstract interface that every LLM provider must implement."""

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Name of the provider (e.g., 'gemini', 'ollama')."""
        pass

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Configured model name identifier."""
        pass

    @abstractmethod
    def generate(self, prompt: str) -> str:
        """Send prompt to LLM and return text response.

        Args:
            prompt: Grounded prompt string containing the retrieved policy context and question.

        Returns:
            The raw string response generated by the LLM.
        """
        pass
